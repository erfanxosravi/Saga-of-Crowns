export function localizeTokenFa(word: string): string {
  if (!word) return word;
  if (NORSE_NAME_MAP_FA[word]) return NORSE_NAME_MAP_FA[word];

  if (word.endsWith('sson')) {
    const base = word.slice(0, -4);
    if (NORSE_NAME_MAP_FA[base]) return `${NORSE_NAME_MAP_FA[base]}‌سون`;
  }
  if (word.endsWith('son')) {
    const base = word.slice(0, -3);
    if (NORSE_NAME_MAP_FA[base]) return `${NORSE_NAME_MAP_FA[base]}‌سون`;
  }
  if (word.endsWith('sdottir')) {
    const base = word.slice(0, -7);
    if (NORSE_NAME_MAP_FA[base]) return `${NORSE_NAME_MAP_FA[base]}‌دوتیر`;
  }
  if (word.endsWith('dottir')) {
    const base = word.slice(0, -6);
    if (NORSE_NAME_MAP_FA[base]) return `${NORSE_NAME_MAP_FA[base]}‌دوتیر`;
  }
  return word;
}

export function formatPersonName(fullName: string, lang: Language): string {
  if (lang === 'en') return fullName;
  if (fullName === 'Halldor Crow-Nose') return 'هالدور کلاغ‌منقار';
  return fullName
    .split(' ')
    .map((part) => localizeTokenFa(part))
    .join(' ');
}

export function formatDynastyName(dynastyName: string, lang: Language): string {
  if (lang === 'en') return dynastyName;
  if (dynastyName.startsWith('House of ')) {
    const founder = dynastyName.slice('House of '.length).trim();
    return `خاندان ${localizeTokenFa(founder)}`;
  }
  return dynastyName;
}

