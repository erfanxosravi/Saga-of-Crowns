interface QuickEventSpec {
  id: string;
  title: string;
  category: EventCategory;
  iconType: EventIconType;
  weight?: number;
  conditions?: EventConditions;
  text: string;
  mildText?: string;
  choices: EventChoice[];
}

function makeQuickEvent(spec: QuickEventSpec): GameEvent {
  return {
    id: spec.id,
    title: spec.title,
    category: spec.category,
    iconType: spec.iconType,
    weight: spec.weight ?? 14,
    conditions: spec.conditions,
    ageMin: spec.conditions?.ageMin,
    ageMax: spec.conditions?.ageMax,
    sex: spec.conditions?.sex,
    classes: spec.conditions?.classes,
    religions: spec.conditions?.religions,
    minTitleRankIndex: spec.conditions?.minTitleRankIndex,
    requiredTraits: spec.conditions?.requiredTraits,
    blockedByTraits: spec.conditions?.blockedByTraits,
    text: spec.text,
    mildText: spec.mildText,
    choices: spec.choices,
  };
}

